/**
 * Canonical persisted-settings defaults builder.
 *
 * CONFIG owns default values. This explicit allowlist owns persistence schema;
 * CONFIG-only runtime constants cannot become persisted accidentally.
 */
import { CONFIG } from './config.js';

function clonePersistedValue(value) {
  if (value === null || typeof value !== 'object') return value;
  if (typeof globalThis.structuredClone === 'function') {
    return globalThis.structuredClone(value);
  }
  return JSON.parse(JSON.stringify(value));
}

